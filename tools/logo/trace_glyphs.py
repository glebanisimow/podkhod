"""Traces the flat brand PNGs (glyphs and the claw badge) into vector drawables and Kotlin path data.

Usage: python tools/logo/trace_glyphs.py <dir with glif-*.png and 01-kogti-disk_square.png>
Needs opencv-python-headless and numpy. Writes:
  app/src/main/res/drawable/{ic_stat_workout,badge_kogti}.xml
  app/src/main/kotlin/app/podkhod/ui/components/BrandGlyphs.kt
The art is flat (ink, amber, bone), so each colour is traced as polygons with holes and filled even-odd.
"""
import os
import sys

import cv2
import numpy as np

ROOT = os.path.join(os.path.dirname(__file__), "..", "..")
RES = os.path.join(ROOT, "app", "src", "main", "res", "drawable")
KT = os.path.join(ROOT, "app", "src", "main", "kotlin", "app", "podkhod", "ui", "components", "BrandGlyphs.kt")

AMBER = (0xFF, 0xAA, 0x1D)
INK = (0x0A, 0x0A, 0x09)
BONE = (0xF2, 0xF0, 0xE8)
# Polygon tolerance in source pixels: invisible at phone sizes, keeps the files small.
EPSILON = 1.6
# Specks below this area (anti-aliasing leftovers) are dropped.
MIN_AREA = 40


def load(path):
    """RGBA image as float arrays; fully transparent pixels count as no colour."""
    # imdecode instead of imread: OpenCV on Windows cannot open non-ASCII paths.
    img = cv2.imdecode(np.fromfile(path, np.uint8), cv2.IMREAD_UNCHANGED)
    if img.shape[2] == 3:
        img = np.dstack([img, np.full(img.shape[:2], 255, np.uint8)])
    rgb = img[:, :, 2::-1].astype(np.float32)
    return rgb, img[:, :, 3]


def mask_of(rgb, alpha, color, palette):
    """Pixels closer to [color] than to any other palette colour, and opaque enough."""
    dist = [np.sum((rgb - np.array(c, np.float32)) ** 2, axis=2) for c in palette]
    nearest = np.argmin(np.stack(dist), axis=0)
    m = (nearest == palette.index(color)) & (alpha > 127)
    return m.astype(np.uint8) * 255


def contours(mask):
    found, _ = cv2.findContours(mask, cv2.RETR_CCOMP, cv2.CHAIN_APPROX_NONE)
    out = []
    for c in found:
        if abs(cv2.contourArea(c)) < MIN_AREA:
            continue
        poly = cv2.approxPolyDP(c, EPSILON, True).reshape(-1, 2)
        if len(poly) >= 3:
            out.append(poly)
    return out


def path_data(polys, dx=0, dy=0, scale=1.0):
    def pt(p):
        x = (p[0] - dx) * scale
        y = (p[1] - dy) * scale
        return f"{x:.1f}".rstrip("0").rstrip(".") + "," + f"{y:.1f}".rstrip("0").rstrip(".")

    return "".join("M" + "L".join(pt(p) for p in poly) + "Z" for poly in polys)


def bbox(polys, margin):
    pts = np.vstack(polys)
    x0, y0 = pts.min(axis=0) - margin
    x1, y1 = pts.max(axis=0) + margin
    return int(x0), int(y0), int(x1), int(y1)


def vector(name, size_dp, vw, vh, body, comment):
    xml = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {comment} Generated by tools/logo/trace_glyphs.py; do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size_dp}dp"
    android:height="{size_dp}dp"
    android:viewportWidth="{vw}"
    android:viewportHeight="{vh}">
{body}</vector>
'''
    with open(os.path.join(RES, name + ".xml"), "w", encoding="utf-8", newline="\n") as f:
        f.write(xml)


def square(x0, y0, x1, y1):
    side = max(x1 - x0, y1 - y0)
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    return cx - side / 2, cy - side / 2, side


def glyph(src, name, color, palette):
    rgb, alpha = load(os.path.join(src, name))
    return contours(mask_of(rgb, alpha, color, palette))


def main(src):
    glyph_palette = [AMBER, BONE, (0, 0, 0)]

    # Status-bar icon: the grandpa with the ice axe, white, square crop with a little air.
    ded = glyph(src, "glif-ded-amber.png", AMBER, glyph_palette)
    x, y, side = square(*bbox(ded, 20))
    d = path_data(ded, x, y, 24 / side)
    vector("ic_stat_workout", 24, 24, 24,
           f'    <path android:fillColor="#FFFFFFFF" android:fillType="evenOdd" android:pathData="{d}" />\n',
           "Workout notification icon: grandpa with the ice axe.")

    # Claw badge for the workout summary: amber disk scratched through, bone figure; the ink square is
    # left out so the badge sits on any dark surface.
    rgb, alpha = load(os.path.join(src, "01-kogti-disk_square.png"))
    palette = [AMBER, INK, BONE]
    amber = contours(mask_of(rgb, alpha, AMBER, palette))
    bone = contours(mask_of(rgb, alpha, BONE, palette))
    x0, y0, x1, y1 = bbox(amber + bone, 8)
    x, y, side = square(x0, y0, x1, y1)
    k = 600 / side
    body = (
        f'    <path android:fillColor="#FFFFAA1D" android:fillType="evenOdd" android:pathData="{path_data(amber, x, y, k)}" />\n'
        f'    <path android:fillColor="#FFF2F0E8" android:fillType="evenOdd" android:pathData="{path_data(bone, x, y, k)}" />\n'
    )
    vector("badge_kogti", 160, 600, 600, body, "Summary badge: claws through the disk, grandpa below.")

    # Single claw strokes and the paw, as path data for Compose: drawn in any colour at any size.
    claws = sorted(glyph(src, "glif-kogti-amber.png", AMBER, glyph_palette), key=lambda p: p[:, 0].min())
    # Every claw on its own 100x100 box, aligned by its own bounding box so they can be laid out freely.
    claw_paths = []
    for c in claws:
        cx, cy, side = square(*bbox([c], 4))
        claw_paths.append(path_data([c], cx, cy, 100 / side))
    paw = glyph(src, "glif-lapa-amber.png", AMBER, glyph_palette)
    px, py, pside = square(*bbox(paw, 8))
    paw_path = path_data(paw, px, py, 100 / pside)

    claw_list = ",\n".join(f'        "{p}"' for p in claw_paths)
    kt = f'''package app.podkhod.ui.components

// Generated by tools/logo/trace_glyphs.py; do not edit by hand.

/** Brand glyphs as SVG path data on a 100×100 box (even-odd fill), for drawing in any colour. */
object BrandGlyphs {{
    /** The four claw strokes of the scratch mark, left to right. */
    val claws: List<String> = listOf(
{claw_list},
    )

    /** The bear paw with its claws. */
    const val PAW: String = "{paw_path}"
}}
'''
    with open(KT, "w", encoding="utf-8", newline="\n") as f:
        f.write(kt)
    print("claws:", len(claws), "paw polys:", len(paw), "ded polys:", len(ded), "badge:", len(amber), len(bone))
    for n in ["ic_stat_workout.xml", "badge_kogti.xml"]:
        print(n, os.path.getsize(os.path.join(RES, n)))
    print("BrandGlyphs.kt", os.path.getsize(KT))


if __name__ == "__main__":
    main(sys.argv[1])
