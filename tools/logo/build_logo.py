"""Builds the app's logo vector drawables from the brand SVGs (straight segments only: M/L/Z).

Usage: python tools/logo/build_logo.py <dir with ded-medved-geo-*.svg>
Writes app/src/main/res/drawable/{logo_krug,logo_krug_on_dark,ic_launcher_foreground,ic_launcher_monochrome,art_noch}.xml.
"""
import os
import re
import sys

AMBER = "#FFFFAA1D"
INK = "#FF0A0A09"
RES = os.path.join(os.path.dirname(__file__), "..", "..", "app", "src", "main", "res", "drawable")


def paths(svg_file):
    text = open(svg_file, encoding="utf-8").read()
    return [(re.sub(r"\s+", " ", d).strip(), fill) for d, fill in re.findall(r'<path d="([^"]*)" fill="([^"]*)"', text)]


def compact(d):
    # "M305.9 414.2 L368.2 394.4" -> "M305.9,414.2L368.2,394.4": about a third smaller, same geometry.
    return re.sub(r"([ML])\s*([-\d.]+)\s+([-\d.]+)\s*", r"\1\2,\3", d).replace(" Z", "Z").replace(" ", "")


def vector(name, size_dp, vw, vh, body, comment):
    xml = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {comment} Generated by tools/logo/build_logo.py; do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size_dp[0]}dp"
    android:height="{size_dp[1]}dp"
    android:viewportWidth="{vw}"
    android:viewportHeight="{vh}">
{body}</vector>
'''
    with open(os.path.join(RES, name + ".xml"), "w", encoding="utf-8", newline="\n") as f:
        f.write(xml)


def path_xml(d, color, indent="    "):
    return f'{indent}<path android:fillColor="{color}" android:pathData="{compact(d)}" />\n'


def color_of(fill):
    return AMBER if fill.upper() == "#FFAA1D" else INK


def main(src):
    krug = paths(os.path.join(src, "ded-medved-geo-krug.svg"))
    noch = paths(os.path.join(src, "ded-medved-geo-noch.svg"))
    ring = "M4,300A296,296 0 1,1 596,300A296,296 0 1,1 4,300Z"

    # Full round badge, as drawn on the brand sheet.
    body = f'    <path android:fillColor="{INK}" android:pathData="{ring}" />\n'
    body += "".join(path_xml(d, color_of(f)) for d, f in krug)
    vector("logo_krug", (48, 48), 600, 600, body, "Round brand badge: grandpa and the bear.")

    # The badge on dark surfaces: its black ring would vanish on ink, so the ring turns amber, drawn on
    # top as a stroke thick enough to read at header size.
    body = f'    <path android:fillColor="{INK}" android:pathData="{ring}" />\n'
    body += "".join(path_xml(d, color_of(f)) for d, f in krug)
    body += f'    <path android:strokeColor="{AMBER}" android:strokeWidth="18" android:pathData="M10,300A290,290 0 1,1 590,300A290,290 0 1,1 10,300Z" />\n'
    vector("logo_krug_on_dark", (48, 48), 600, 600, body, "Round brand badge for dark surfaces (amber ring).")

    # Adaptive launcher foreground: the badge without its outer ring, sized so the dark background shows
    # as the ring inside a circle mask (amber disk 64 dp of the 72 dp visible area).
    scale = 32 / 288
    shift = 54 - 300 * scale
    inner = "".join(path_xml(d, color_of(f), "        ") for d, f in krug)
    body = f'    <group android:scaleX="{scale:.5f}" android:scaleY="{scale:.5f}" android:translateX="{shift:.4f}" android:translateY="{shift:.4f}">\n{inner}    </group>\n'
    vector("ic_launcher_foreground", (108, 108), 108, 108, body, "Launcher icon foreground.")

    # Themed (monochrome) icon: only alpha counts, so it is the silhouettes and the ground.
    inner = "".join(path_xml(d, INK, "        ") for d, f in krug if f.upper() != "#FFAA1D")
    body = f'    <group android:scaleX="{scale:.5f}" android:scaleY="{scale:.5f}" android:translateX="{shift:.4f}" android:translateY="{shift:.4f}">\n{inner}    </group>\n'
    vector("ic_launcher_monochrome", (108, 108), 108, 108, body, "Themed launcher icon.")

    # Night scene without its background, cropped to the figures: amber on whatever surface it sits on.
    top, height = 90, 470
    inner = "".join(path_xml(d, AMBER, "        ") for d, f in noch)
    body = f'    <group android:translateY="-{top}">\n{inner}    </group>\n'
    vector("art_noch", (300, 235), 600, height, body, "Night scene illustration for headers and empty states.")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/Downloads/ded-medved-geo"))
